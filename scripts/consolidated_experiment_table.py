#!/usr/bin/env python
"""Consolidated logical-to-physical experiment table.

Run AFTER training (and, if available, after local evaluation) to produce one
table covering every logical experiment ID, which physical run satisfies it,
parameters, runtime, clean/corruption metrics and completion status.

    python scripts/consolidated_experiment_table.py \
        --campaign results/campaign \
        --out docs/CONSOLIDATED_EXPERIMENT_TABLE.md

Reads only what exists. Missing evaluation metrics print as `--` and are never
inferred. Test-set columns stay empty until local evaluation has run.
"""

from __future__ import annotations

import argparse
import csv
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "src"))
from aetfpe.campaign import EXPERIMENTS, REUSE, build_matrix  # noqa: E402

# Logical ID -> the physical run whose checkpoint satisfies it.
LOGICAL = [(e["id"], e["id"], e["title"], e["group"], e["priority"]) for e in EXPERIMENTS] + [
    ("F3", "A3", "Concat + projection fusion (= A3)", "F", "-"),
    ("F5", "A5", "AE fusion, denoising (= A5)", "F", "-"),
    ("F5_clean", "D1", "AE fusion, clean objective (= D1)", "F", "-"),
]


def fmt(v, spec=".4f"):
    if v in (None, "", "-"):
        return "--"
    try:
        return format(float(v), spec)
    except (TypeError, ValueError):
        return str(v)


def load(run_dir: str) -> dict:
    """Everything recorded for one physical run. Absent stays absent."""
    out: dict = {}
    s = os.path.join(run_dir, "train_summary.json")
    if os.path.exists(s):
        try:
            out["summary"] = json.load(open(s))
        except Exception:  # noqa: BLE001
            pass
    m = os.path.join(run_dir, "metrics.csv")
    if os.path.exists(m):
        try:
            rows = list(csv.DictReader(open(m)))
            out["metrics"] = rows
            joint = [r for r in rows if r.get("stage") != "ae_warmup"] or rows
            v5 = [float(r["val_top5"]) for r in joint if r.get("val_top5")]
            out["best_val_top5"] = max(v5) if v5 else None
            out["epochs_done"] = len(rows)
        except Exception:  # noqa: BLE001
            pass
    e = os.path.join(run_dir, "eval_summary.json")
    if os.path.exists(e):
        try:
            out["eval"] = json.load(open(e))
        except Exception:  # noqa: BLE001
            pass
    return out


def severity_means(ev: dict) -> dict:
    """Mean top-1 per severity across the new benchmark families."""
    fam = ("gaussian_noise", "gaussian_blur", "brightness", "jpeg")
    got: dict[str, list[float]] = {"easy": [], "medium": [], "hard": []}
    for key, val in (ev or {}).items():
        if not isinstance(val, dict):
            continue
        for sev in got:
            for f in fam:
                node = val.get(f"{f}/{sev}") or val.get(f, {}).get(sev) if isinstance(val, dict) else None
                if isinstance(node, dict) and node.get("top1") is not None:
                    got[sev].append(float(node["top1"]))
    return {k: (sum(v) / len(v) if v else None) for k, v in got.items()}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--campaign", default="results/campaign",
                    help="directory holding one folder per physical run")
    ap.add_argument("--manifest", default=None, help="campaign_manifest.json (optional)")
    ap.add_argument("--out", default="docs/CONSOLIDATED_EXPERIMENT_TABLE.md")
    args = ap.parse_args()

    manifest = {}
    mp = args.manifest or os.path.join(args.campaign, "campaign_manifest.json")
    if os.path.exists(mp):
        try:
            manifest = json.load(open(mp)).get("runs", {})
        except Exception:  # noqa: BLE001
            pass

    params = {r["id"]: r for r in build_matrix()}
    data = {rid: load(os.path.join(args.campaign, rid))
            for rid in {p for _, p, _, _, _ in LOGICAL}}

    L = []
    A = L.append
    A("# Consolidated Experiment Table — logical IDs to physical runs\n")
    A(f"**Generated by:** `scripts/consolidated_experiment_table.py` from "
      f"`{args.campaign}`. Only recorded values appear; `--` means the artifact "
      f"does not exist and nothing was inferred.\n")

    n_log = len(LOGICAL)
    n_phys = len({p for _, p, _, _, _ in LOGICAL})
    n_cfg = len([e for e in EXPERIMENTS if not e["config"].startswith("configs/efficient")])
    A(f"**{n_log} logical experiment IDs** are satisfied by **{n_phys} unique physical "
      f"trainings** — {n_cfg} from `configs/` plus 3 Efficient arms — because "
      f"{len(REUSE)} logical IDs reuse another run's checkpoint.\n")

    A("## 1. Full table\n")
    A("| Logical ID | Physical run | Experiment | Grp | Pri | Total params | Trainable | "
      "Status | Epochs | Runtime | Best val top-1 | Best val top-5 | Clean test top-1 | "
      "Easy | Moderate | Hard |")
    A("|---|---|---|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for lid, pid, title, grp, pri in LOGICAL:
        d = data.get(pid, {})
        summ = d.get("summary", {})
        man = manifest.get(pid, {})
        pr = params.get(pid, {})
        ev = d.get("eval", {})
        sev = severity_means(ev)
        clean = ((ev.get("test_clean") or {}).get("top1")) if isinstance(ev, dict) else None
        status = man.get("status") or summ.get("status") or ("--" if not d else "COMPLETED")
        if lid != pid:
            status = f"REUSE → {pid}"
        rt = man.get("runtime_s") or summ.get("train_seconds")
        A(f"| **{lid}** | {pid} | {title} | {grp} | {pri} | "
          f"{pr.get('params', 0):,} | {pr.get('trainable_params', 0):,} | {status} | "
          f"{d.get('epochs_done', '--')} | "
          f"{(f'{float(rt)/3600:.2f} h' if rt else '--')} | "
          f"{fmt(summ.get('best_val_top1') or man.get('best_val_top1'))} | "
          f"{fmt(d.get('best_val_top5') or man.get('best_val_top5'))} | "
          f"{fmt(clean)} | {fmt(sev.get('easy'))} | {fmt(sev.get('medium'))} | "
          f"{fmt(sev.get('hard'))} |")
    A("")

    A("## 2. Reuse map — verified from config signatures\n")
    A("| Logical ID | Served by | Why |")
    A("|---|---|---|")
    for logical, (src, why) in REUSE.items():
        A(f"| {logical} | **{src}** | {why} |")
    A("\nConfirmed by `scripts/print_run_matrix.py`, which compares the resolved model "
      "config, protocol and train block — not by annotation.\n")
    A("`A1` (PE-only) additionally serves **both** method families: with no transformer "
      "branch the Original and Efficient variants are the same model.\n")

    A("## 3. Completion summary\n")
    counts: dict[str, int] = {}
    for lid, pid, *_ in LOGICAL:
        st = "REUSE" if lid != pid else (
            manifest.get(pid, {}).get("status")
            or (data.get(pid, {}).get("summary", {}) or {}).get("status")
            or "NOT RUN")
        counts[st] = counts.get(st, 0) + 1
    A("| Status | Logical IDs |")
    A("|---|---:|")
    for k, v in sorted(counts.items()):
        A(f"| {k} | {v} |")
    A("")

    A("## 4. Reading rules\n")
    for s in (
        "**Two methods, never merged.** Original AE-TFPE (A5 / D1 / F-series, ViT-B/16 + "
        "image-space AE) is the reference formulation. Efficient AE-TFPE (E5 / E3 / E7, "
        "MobileViT-XXS stage 2 + feature-space AE) is the Major-Revision improvement.",
        "**Protocol B only.** Historical detection-style Protocol A numbers are not "
        "comparable and must never be differenced against anything here.",
        "**Validation selected the checkpoints; test did not.** Test columns are reported, "
        "never used for selection.",
        "**Training wall-clock is not architecture evidence** unless the environments "
        "match. Deployment latency, throughput and memory come only from the Tesla T4 "
        "benchmarks in `docs/evidence/`.",
        "**Easy / Moderate / Hard** are mean top-1 across gaussian_noise, gaussian_blur, "
        "brightness and jpeg at that severity.",
    ):
        A(f"- {s}")
    A("")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    open(args.out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"\nwrote {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
